const golden = "../../testdata/openapi.golden.json"

func runCLI(t *testing.T, stdin string, args ...string) (code int, stdout, stderr string) {
	t.Helper()
	var out, errb bytes.Buffer
	code = run(args, strings.NewReader(stdin), &out, &errb)
	return code, out.String(), errb.String()
}

func TestGenAndCheck(t *testing.T) {
	dir := t.TempDir()
	client := filepath.Join(dir, "api.ts")

	code, stdout, stderr := runCLI(t, "", "gen", "ts", "-spec", golden, "-o", client)
	if code != 0 || stdout != "" || stderr != "" {
		t.Fatalf("gen: code %d, stdout %q, stderr %q", code, stdout, stderr)
	}
	written, err := os.ReadFile(client)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(written), "// Code generated by tack from Pet API 1.2.3. DO NOT EDIT.") {
		t.Fatalf("unexpected client:\n%s", written)
	}

	code, stdout, _ = runCLI(t, "", "gen", "ts", "-spec", golden)
	if code != 0 || stdout != string(written) {
		t.Fatalf("gen to stdout: code %d, differs from file", code)
	}

	code, stdout, stderr = runCLI(t, "", "check", "-spec", golden, client)
	if code != 0 || stdout != client+" is up to date\n" || stderr != "" {
		t.Fatalf("check fresh: code %d, stdout %q, stderr %q", code, stdout, stderr)
	}

	if err := os.WriteFile(client, append(written, "// edited\n"...), 0o644); err != nil {
		t.Fatal(err)
	}
	code, stdout, stderr = runCLI(t, "", "check", "-spec", golden, client)
	if code != 1 || stdout != "" || !strings.Contains(stderr, "TypeScript client is stale") {
		t.Fatalf("check stale: code %d, stdout %q, stderr %q", code, stdout, stderr)
	}

	code, _, stderr = runCLI(t, "", "check", "-spec", golden, filepath.Join(dir, "missing.ts"))
	if code != 1 || !strings.Contains(stderr, "does not exist") {
		t.Fatalf("check missing: code %d, stderr %q", code, stderr)
	}
}

func TestSpecSources(t *testing.T) {
	spec, err := os.ReadFile(golden)
	if err != nil {
		t.Fatal(err)
	}
	fromFile, _, _ := runCLI(t, "", "gen", "ts", "-spec", golden)
	if fromFile != 0 {
		t.Fatal("gen from file failed")
	}
	_, want, _ := runCLI(t, "", "gen", "ts", "-spec", golden)

	code, got, stderr := runCLI(t, string(spec), "gen", "ts", "-spec", "-")
	if code != 0 || got != want {
		t.Fatalf("stdin: code %d, stderr %q", code, stderr)
	}

	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path == "/missing" {
			http.NotFound(w, r)
			return
		}
		if r.Header.Get("Accept") != "application/json" {
			t.Errorf("Accept header %q", r.Header.Get("Accept"))
		}
		w.Header().Set("Content-Type", "application/json")
		_, _ = w.Write(spec)
	}))
	defer srv.Close()
	code, got, stderr = runCLI(t, "", "gen", "ts", "-spec", srv.URL+"/openapi.json")
	if code != 0 || got != want {
		t.Fatalf("url: code %d, stderr %q", code, stderr)
	}
	code, _, stderr = runCLI(t, "", "gen", "ts", "-spec", srv.URL+"/missing")
	if code != 1 || !strings.Contains(stderr, "404") {
		t.Fatalf("url 404: code %d, stderr %q", code, stderr)
	}
}

func TestBadInput(t *testing.T) {
	dir := t.TempDir()
	notJSON := filepath.Join(dir, "spec.yaml")
	if err := os.WriteFile(notJSON, []byte("openapi: 3.1.0\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	noPaths := filepath.Join(dir, "empty.json")
	if err := os.WriteFile(noPaths, []byte(`{"openapi":"3.1.0","info":{"title":"x","version":"1"}}`), 0o644); err != nil {
		t.Fatal(err)
	}
	badDoc := filepath.Join(dir, "bad.json")
	if err := os.WriteFile(badDoc, []byte(`{"paths":{"/a":{"get":{"operationId":"a b","responses":{"200":{"description":"OK"}}}}}}`), 0o644); err != nil {
		t.Fatal(err)
	}
	tests := []struct {
		name  string
		args  []string
		code  int
		want  string
		where string // stdout or stderr
	}{
		{"no args", nil, 2, "Usage:", "stderr"},
		{"help", []string{"help"}, 0, "Usage:", "stdout"},
		{"flag help", []string{"gen", "ts", "-h"}, 0, "", "stdout"},
		{"unknown command", []string{"build"}, 1, `unknown command "build"`, "stderr"},
		{"gen without target", []string{"gen"}, 2, "gen needs a target", "stderr"},
		{"gen unknown target", []string{"gen", "go"}, 2, "the only one is ts", "stderr"},
		{"gen extra arg", []string{"gen", "ts", "-spec", golden, "extra"}, 2, `unexpected argument "extra"`, "stderr"},
		{"gen unknown flag", []string{"gen", "ts", "-x"}, 2, "flag provided but not defined", "stderr"},
		{"gen without spec", []string{"gen", "ts"}, 2, "-spec is required", "stderr"},
		{"check without file", []string{"check", "-spec", golden}, 2, "check needs the client file", "stderr"},
		{"missing spec file", []string{"gen", "ts", "-spec", filepath.Join(dir, "nope.json")}, 1, "reading OpenAPI document", "stderr"},
		{"spec not json", []string{"gen", "ts", "-spec", notJSON}, 1, "parsing OpenAPI document", "stderr"},
		{"spec without paths", []string{"gen", "ts", "-spec", noPaths}, 1, "no paths", "stderr"},
		{"invalid operation", []string{"gen", "ts", "-spec", badDoc}, 1, "not a TypeScript identifier", "stderr"},
		{"unwritable output", []string{"gen", "ts", "-spec", golden, "-o", filepath.Join(dir, "no", "such", "dir.ts")}, 1, "writing client", "stderr"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			code, stdout, stderr := runCLI(t, "", tt.args...)
			got := stderr
			if tt.where == "stdout" {
				got = stdout
			}
			if code != tt.code || !strings.Contains(got, tt.want) {
				t.Fatalf("code %d, stdout %q, stderr %q; want code %d containing %q", code, stdout, stderr, tt.code, tt.want)
			}
		})
	}
}
