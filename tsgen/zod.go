// GenerateZod returns Zod schemas for doc: one per component schema and one
// per operation input, carrying the same rules the server enforces (bounds,
// lengths, patterns, enums, formats), so a form can validate before a request
// is sent. The file imports "zod" and works with Zod 3.23 and later, Zod 4
// included. Each schema exports a value and a type of the same name:
//
//	import { PetInput } from "./schemas";
//	const result = PetInput.safeParse(form);
//
// Like Generate, it reads only the document and is deterministic; see
// CheckZod for keeping the file fresh.
func GenerateZod(doc *openapi.Document) ([]byte, error) {
	g := &generator{doc: doc, names: map[string]string{}, taken: map[string]string{}}
	g.taken["z"] = "the zod import"
	if err := g.collect(); err != nil {
		return nil, fmt.Errorf("tsgen: %w", err)
	}
	z := &zodGen{generator: g}
	z.emit()
	if g.err != nil {
		return nil, fmt.Errorf("tsgen: %w", g.err)
	}
	return g.buf.Bytes(), nil
}

// CheckZod is Check for the file GenerateZod produces.
func CheckZod(doc *openapi.Document, path string) error {
	return check(path, func() ([]byte, error) { return GenerateZod(doc) }, "tsgen.GenerateZod or `tack gen zod`")
}

type zodGen struct {
	*generator
	recursive map[string]bool // component names that take part in a reference cycle
}

func (z *zodGen) emit() {
	fmt.Fprintf(&z.buf, "// Code generated by tack from %s %s. DO NOT EDIT.\n", z.doc.Info.Title, z.doc.Info.Version)
	z.buf.WriteString("// Zod schemas with the rules the server enforces; regenerate them from the OpenAPI document.\n\n")
	z.buf.WriteString("import { z } from \"zod\";\n\n")
	for _, name := range z.order() {
		z.emitSchema(name, z.doc.Components.Schemas[name])
	}
	for _, o := range z.ops {
		if !o.hasInput() {
			continue
		}
		var props []string
		for _, p := range o.params {
			props = append(props, z.propertyLine(p.Name, p.Schema, p.Required))
		}
		if o.body != nil {
			props = append(props, z.propertyLine("body", o.bodySchema, o.body.Required))
		}
		fmt.Fprintf(&z.buf, "export const %sInput = z.object({\n  %s,\n});\nexport type %sInput = z.infer<typeof %sInput>;\n\n", o.typeName, strings.Join(props, ",\n  "), o.typeName, o.typeName)
	}
	b := strings.TrimRight(z.buf.String(), "\n") + "\n"
	z.buf.Reset()
	z.buf.WriteString(b)
}

func (z *zodGen) emitSchema(name string, s *openapi.Schema) {
	ts := z.names[name]
	if z.recursive[name] {
		// A schema in a cycle needs an explicit type for z.lazy; the type is
		// written the way the client writes it.
		if isPlainObject(s) {
			z.emitInterface(ts, s)
			z.buf.Truncate(z.buf.Len() - 1)
		} else {
			fmt.Fprintf(&z.buf, "export type %s = %s;\n", ts, z.typeOf(s))
		}
		fmt.Fprintf(&z.buf, "export const %s: z.ZodType<%s> = z.lazy(() => %s);\n\n", ts, ts, z.expr(s, true))
		return
	}
	fmt.Fprintf(&z.buf, "export const %s = %s;\nexport type %s = z.infer<typeof %s>;\n\n", ts, z.expr(s, true), ts, ts)
}

// order returns the component names so that every schema comes after the
// schemas it references, except inside cycles, whose members use z.lazy.
func (z *zodGen) order() []string {
	var schemas map[string]*openapi.Schema
	if z.doc.Components != nil {
		schemas = z.doc.Components.Schemas
	}
	deps := map[string][]string{}
	for _, name := range sortedKeys(schemas) {
		deps[name] = refsIn(schemas[name], nil)
	}
	z.recursive = map[string]bool{}
	for name := range deps {
		if reaches(deps, name, name, map[string]bool{}) {
			z.recursive[name] = true
		}
	}
	var (
		out     []string
		visited = map[string]bool{}
		visit   func(string)
	)
	visit = func(name string) {
		if visited[name] {
			return
		}
		visited[name] = true
		for _, d := range deps[name] {
			if _, ok := deps[d]; ok {
				visit(d)
			}
		}
		out = append(out, name)
	}
	for _, name := range sortedKeys(deps) {
		visit(name)
	}
	return out
}

// refsIn lists the component names s references, sorted and without repeats.
func refsIn(s *openapi.Schema, acc []string) []string {
	if s == nil {
		return acc
	}
	if s.Ref != "" {
		name := strings.TrimPrefix(s.Ref, "#/components/schemas/")
		if !contains(acc, name) {
			acc = append(acc, name)
		}
	}
	for _, list := range [][]*openapi.Schema{s.AllOf, s.OneOf, s.AnyOf} {
		for _, p := range list {
			acc = refsIn(p, acc)
		}
	}
	for _, name := range sortedKeys(s.Properties) {
		acc = refsIn(s.Properties[name], acc)
	}
	acc = refsIn(s.Items, acc)
	acc = refsIn(s.AdditionalProperties, acc)
	sort.Strings(acc)
	return acc
}

// reaches reports whether target is reachable from the dependencies of from.
func reaches(deps map[string][]string, from, target string, seen map[string]bool) bool {
	for _, d := range deps[from] {
		if d == target {
			return true
		}
		if !seen[d] {
			seen[d] = true
			if reaches(deps, d, target, seen) {
				return true
			}
		}
	}
	return false
}

// propertyLine writes `key: schema` with optional, default, and description.
func (z *zodGen) propertyLine(name string, s *openapi.Schema, required bool) string {
	e := z.expr(s, false)
	switch {
	case s != nil && s.Default != nil:
		e += ".default(" + literal(s.Default) + ")"
	case !required:
		e += ".optional()"
	}
	return propertyKey(name) + ": " + e
}

// expr returns the Zod expression for s. Top-level objects span several lines.
func (z *zodGen) expr(s *openapi.Schema, top bool) string {
	e := z.base(s, top)
	if s == nil {
		return e
	}
	if s.Nullable {
		e += ".nullable()"
	}
	if s.Description != "" {
		e += ".describe(" + tsString(s.Description) + ")"
	}
	return e
}

func (z *zodGen) base(s *openapi.Schema, top bool) string {
	switch {
	case s == nil:
		return "z.unknown()"
	case s.Ref != "":
		return z.typeOf(&openapi.Schema{Ref: s.Ref})
	case len(s.AllOf) > 0:
		e := z.expr(s.AllOf[0], false)
		for _, p := range s.AllOf[1:] {
			e += ".and(" + z.expr(p, false) + ")"
		}
		return e
	case len(s.OneOf) > 0 || len(s.AnyOf) > 0:
		var parts []string
		for _, p := range append(s.OneOf, s.AnyOf...) {
			parts = append(parts, z.expr(p, false))
		}
		if len(parts) == 1 {
			return parts[0]
		}
		return "z.union([" + strings.Join(parts, ", ") + "])"
	case len(s.Enum) > 0:
		return zodEnum(s.Enum)
	}
	switch s.Type {
	case "string":
		if s.Format == "binary" {
			return "z.instanceof(Blob)"
		}
		e := "z.string()"
		switch s.Format {
		case "email":
			e += ".email()"
		case "uuid":
			e += ".uuid()"
		case "uri":
			e += ".url()"
		case "date-time":
			e += ".datetime()"
		}
		if s.MinLength != nil {
			e += ".min(" + strconv.Itoa(*s.MinLength) + ")"
		}
		if s.MaxLength != nil {
			e += ".max(" + strconv.Itoa(*s.MaxLength) + ")"
		}
		if s.Pattern != "" {
			e += ".regex(new RegExp(" + tsString(s.Pattern) + "))"
		}
		return e
	case "integer", "number":
		e := "z.number()"
		if s.Type == "integer" {
			e += ".int()"
		}
		if s.Minimum != nil {
			e += ".min(" + number(*s.Minimum) + ")"
		}
		if s.ExclusiveMinimum != nil {
			e += ".gt(" + number(*s.ExclusiveMinimum) + ")"
		}
		if s.Maximum != nil {
			e += ".max(" + number(*s.Maximum) + ")"
		}
		if s.ExclusiveMaximum != nil {
			e += ".lt(" + number(*s.ExclusiveMaximum) + ")"
		}
		return e
	case "boolean":
		return "z.boolean()"
	case "null":
		return "z.null()"
	case "array":
		e := "z.array(" + z.expr(s.Items, false) + ")"
		if s.MinItems != nil {
			e += ".min(" + strconv.Itoa(*s.MinItems) + ")"
		}
		if s.MaxItems != nil {
			e += ".max(" + strconv.Itoa(*s.MaxItems) + ")"
		}
		return e
	case "object", "":
		if len(s.Properties) == 0 {
			switch {
			case s.AdditionalProperties != nil:
				return "z.record(z.string(), " + z.expr(s.AdditionalProperties, false) + ")"
			case s.Type == "object":
				return "z.record(z.string(), z.unknown())"
			default:
				return "z.unknown()"
			}
		}
		var props []string
		for _, name := range sortedKeys(s.Properties) {
			props = append(props, z.propertyLine(name, s.Properties[name], contains(s.Required, name)))
		}
		e := "z.object({ " + strings.Join(props, ", ") + " })"
		if top {
			e = "z.object({\n  " + strings.Join(props, ",\n  ") + ",\n})"
		}
		if s.AdditionalProperties != nil {
			e += ".catchall(" + z.expr(s.AdditionalProperties, false) + ")"
		}
		return e
	}
	z.fail(fmt.Errorf("unsupported schema type %q", s.Type))
	return "z.unknown()"
}

// zodEnum writes z.enum for string values and a union of literals otherwise.
func zodEnum(values []any) string {
	var lits []string
	allStrings := true
	for _, v := range values {
		if v == nil {
			continue
		}
		if _, ok := v.(string); !ok {
			allStrings = false
		}
		lits = append(lits, literal(v))
	}
	switch {
	case len(lits) == 0:
		return "z.null()"
	case len(lits) == 1:
		return "z.literal(" + lits[0] + ")"
	case allStrings:
		return "z.enum([" + strings.Join(lits, ", ") + "])"
	}
	for i, l := range lits {
		lits[i] = "z.literal(" + l + ")"
	}
	return "z.union([" + strings.Join(lits, ", ") + "])"
}

func number(f float64) string { return strconv.FormatFloat(f, 'g', -1, 64) }
