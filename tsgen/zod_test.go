func i(v int) *int { return &v }

func TestZodExpr(t *testing.T) {
	z := &zodGen{generator: &generator{names: map[string]string{"Pet": "Pet"}}}
	tests := []struct {
		name string
		in   *openapi.Schema
		want string
	}{
		{"nil", nil, "z.unknown()"},
		{"any", &openapi.Schema{}, "z.unknown()"},
		{"string", &openapi.Schema{Type: "string"}, "z.string()"},
		{"string rules", &openapi.Schema{Type: "string", MinLength: i(1), MaxLength: i(5), Pattern: `^a/b\d$`}, `z.string().min(1).max(5).regex(new RegExp("^a/b\\d$"))`},
		{"email", &openapi.Schema{Type: "string", Format: "email"}, "z.string().email()"},
		{"uuid", &openapi.Schema{Type: "string", Format: "uuid"}, "z.string().uuid()"},
		{"uri", &openapi.Schema{Type: "string", Format: "uri"}, "z.string().url()"},
		{"date-time", &openapi.Schema{Type: "string", Format: "date-time"}, "z.string().datetime()"},
		{"unknown format", &openapi.Schema{Type: "string", Format: "hostname"}, "z.string()"},
		{"integer bounds", &openapi.Schema{Type: "integer", Minimum: f(1), Maximum: f(10)}, "z.number().int().min(1).max(10)"},
		{"number exclusive", &openapi.Schema{Type: "number", ExclusiveMinimum: f(0.5), ExclusiveMaximum: f(2)}, "z.number().gt(0.5).lt(2)"},
		{"boolean", &openapi.Schema{Type: "boolean"}, "z.boolean()"},
		{"null", &openapi.Schema{Type: "null"}, "z.null()"},
		{"nullable", &openapi.Schema{Type: "string", Nullable: true}, "z.string().nullable()"},
		{"described", &openapi.Schema{Type: "string", Description: "A \"name\""}, `z.string().describe("A \"name\"")`},
		{"ref", ref("Pet"), "Pet"},
		{"array", &openapi.Schema{Type: "array", Items: ref("Pet"), MinItems: i(1), MaxItems: i(3)}, "z.array(Pet).min(1).max(3)"},
		{"string enum", &openapi.Schema{Type: "string", Enum: []any{"a", "b"}}, `z.enum(["a", "b"])`},
		{"single enum", &openapi.Schema{Type: "string", Enum: []any{"a"}}, `z.literal("a")`},
		{"mixed enum", &openapi.Schema{Enum: []any{1, "a", nil}}, `z.union([z.literal(1), z.literal("a")])`},
		{"null enum", &openapi.Schema{Enum: []any{nil}}, "z.null()"},
		{"map", &openapi.Schema{Type: "object", AdditionalProperties: &openapi.Schema{Type: "integer"}}, "z.record(z.string(), z.number().int())"},
		{"empty object", &openapi.Schema{Type: "object"}, "z.record(z.string(), z.unknown())"},
		{"object", &openapi.Schema{Type: "object", Properties: map[string]*openapi.Schema{
			"b": {Type: "string", Default: "x"}, "a": {Type: "integer"}, "c-d": {Type: "boolean"},
		}, Required: []string{"a"}}, `z.object({ a: z.number().int(), b: z.string().default("x"), "c-d": z.boolean().optional() })`},
		{"object with extras", &openapi.Schema{Type: "object", Properties: map[string]*openapi.Schema{"a": {Type: "string"}}, AdditionalProperties: &openapi.Schema{}},
			"z.object({ a: z.string().optional() }).catchall(z.unknown())"},
		{"allOf", &openapi.Schema{AllOf: []*openapi.Schema{ref("Pet"), {Type: "object", Properties: map[string]*openapi.Schema{"x": {Type: "string"}}}, ref("Pet")}},
			"Pet.and(z.object({ x: z.string().optional() })).and(Pet)"},
		{"oneOf", &openapi.Schema{OneOf: []*openapi.Schema{{Type: "string"}, {Type: "integer"}}}, "z.union([z.string(), z.number().int()])"},
		{"single anyOf", &openapi.Schema{AnyOf: []*openapi.Schema{{Type: "string"}}}, "z.string()"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := z.expr(tt.in, false); got != tt.want {
				t.Errorf("got %s, want %s", got, tt.want)
			}
			if z.err != nil {
				t.Fatal(z.err)
			}
		})
	}
	z.expr(&openapi.Schema{Type: "file"}, false)
	if z.err == nil {
		t.Fatal("want error for unsupported type")
	}
}

func TestGenerateZod(t *testing.T) {
	doc := testDoc(map[string]*openapi.PathItem{
		"/": {Get: &openapi.Operation{Responses: map[string]*openapi.Response{"204": {}}}},
		"/nodes": {Post: &openapi.Operation{
			Parameters:  []*openapi.Parameter{{Name: "dry", In: "query", Schema: &openapi.Schema{Type: "boolean", Default: false}}},
			RequestBody: &openapi.RequestBody{Required: true, Content: map[string]*openapi.MediaType{"application/json": {Schema: ref("Node")}}},
			Responses:   jsonOK(ref("Node")),
		}},
	}, map[string]*openapi.Schema{
		// Node -> Leaf -> Node is a cycle; Tag is referenced by Node and must come first.
		"Node": {Type: "object", Description: "A tree.", Properties: map[string]*openapi.Schema{
			"tag":      ref("Tag"),
			"children": {Type: "array", Items: ref("Leaf")},
		}, Required: []string{"tag"}},
		"Leaf":  {OneOf: []*openapi.Schema{ref("Node"), {Type: "string"}}},
		"Tag":   {Type: "string", Enum: []any{"a", "b"}},
		"Alone": {Type: "integer"},
	})
	out, err := GenerateZod(doc)
	if err != nil {
		t.Fatal(err)
	}
	ts := string(out)
	for _, want := range []string{
		"// Code generated by tack from T 1. DO NOT EDIT.\n// Zod schemas with the rules the server enforces; regenerate them from the OpenAPI document.\n\nimport { z } from \"zod\";\n\n",
		"export const Alone = z.number().int();\nexport type Alone = z.infer<typeof Alone>;\n",
		"export const Tag = z.enum([\"a\", \"b\"]);\nexport type Tag = z.infer<typeof Tag>;\n",
		"export type Leaf = Node | string;\nexport const Leaf: z.ZodType<Leaf> = z.lazy(() => z.union([Node, z.string()]));\n",
		"/** A tree. */\nexport interface Node {\n  children?: Leaf[];\n  tag: Tag;\n}\nexport const Node: z.ZodType<Node> = z.lazy(() => z.object({\n  children: z.array(Leaf).optional(),\n  tag: Tag,\n}).describe(\"A tree.\"));\n",
		"export const PostNodesInput = z.object({\n  dry: z.boolean().default(false),\n  body: Node,\n});\nexport type PostNodesInput = z.infer<typeof PostNodesInput>;\n",
	} {
		if !strings.Contains(ts, want) {
			t.Errorf("output lacks:\n%s\n\nfull output:\n%s", want, ts)
		}
	}
	if strings.Index(ts, "export const Tag ") > strings.Index(ts, "export const Node") {
		t.Errorf("dependencies outside the cycle should come first:\n%s", ts)
	}
	if strings.Contains(ts, "GetInput") || !strings.HasSuffix(ts, ";\n") || strings.HasSuffix(ts, "\n\n") {
		t.Errorf("no input for a bare operation and exactly one trailing newline:\n%s", ts)
	}
	again, _ := GenerateZod(doc)
	if string(again) != ts {
		t.Fatal("output is not deterministic")
	}
}

func TestGenerateZodErrors(t *testing.T) {
	doc := testDoc(map[string]*openapi.PathItem{}, map[string]*openapi.Schema{"z": {Type: "string"}})
	if _, err := GenerateZod(doc); err == nil || !strings.Contains(err.Error(), "the zod import") {
		t.Fatalf("schema named z: got %v", err)
	}
	doc = testDoc(map[string]*openapi.PathItem{"/": {Post: &openapi.Operation{
		RequestBody: &openapi.RequestBody{Content: map[string]*openapi.MediaType{"application/json": {Schema: ref("Missing")}}},
		Responses:   jsonOK(nil),
	}}}, nil)
	if _, err := GenerateZod(doc); err == nil || !strings.Contains(err.Error(), "Missing") {
		t.Fatalf("missing ref: got %v", err)
	}
	doc = testDoc(map[string]*openapi.PathItem{}, map[string]*openapi.Schema{"Bad": {Type: "file"}})
	if _, err := GenerateZod(doc); err == nil || !strings.Contains(err.Error(), `"file"`) {
		t.Fatalf("unsupported type: got %v", err)
	}
}

func TestCheckZod(t *testing.T) {
	doc := testDoc(map[string]*openapi.PathItem{}, map[string]*openapi.Schema{"A": {Type: "string"}})
	want, err := GenerateZod(doc)
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(t.TempDir(), "schemas.ts")
	if err := CheckZod(doc, path); !errors.Is(err, ErrStale) || !strings.Contains(err.Error(), "tack gen zod") {
		t.Fatalf("missing: got %v", err)
	}
	if err := os.WriteFile(path, want, 0o644); err != nil {
		t.Fatal(err)
	}
	if err := CheckZod(doc, path); err != nil {
		t.Fatalf("fresh: got %v", err)
	}
	if err := os.WriteFile(path, append(want, '\n'), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := CheckZod(doc, path); !errors.Is(err, ErrStale) {
		t.Fatalf("stale: got %v", err)
	}
}
