package tsgen

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/raven-clown/tack/openapi"
)

// emit writes the whole file: header, Client, runtime, operation types, and
// schema types.
func (g *generator) emit() {
	fmt.Fprintf(&g.buf, "// Code generated by tack from %s %s. DO NOT EDIT.\n", g.doc.Info.Title, g.doc.Info.Version)
	g.buf.WriteString("// Regenerate it from the OpenAPI document; edits are lost on the next run.\n\n")
	g.emitClient()
	g.emitRuntime()
	for _, o := range g.ops {
		g.emitOperationTypes(o)
	}
	g.emitSchemas()
	// One trailing newline, no more.
	b := strings.TrimRight(g.buf.String(), "\n") + "\n"
	g.buf.Reset()
	g.buf.WriteString(b)
}

func (g *generator) emitClient() {
	g.buf.WriteString("export class Client {\n")
	g.buf.WriteString("  constructor(private readonly options: ClientOptions = {}) {}\n")
	for _, o := range g.ops {
		g.buf.WriteString("\n")
		g.emitMethod(o)
	}
	g.buf.WriteString("\n" + clientMethods + "}\n\n")
}

func (g *generator) emitMethod(o *operation) {
	var notes []string
	if o.summary != "" {
		notes = append(notes, o.summary)
	}
	if o.description != "" {
		notes = append(notes, o.description)
	}
	if len(o.cookies) > 0 {
		word := "Cookie"
		if len(o.cookies) > 1 {
			word = "Cookies"
		}
		notes = append(notes, fmt.Sprintf("%s %s: not part of the input; the browser sends it when the request has `credentials: \"include\"`.", word, strings.Join(quoteAll(o.cookies), ", ")))
	}
	if o.deprecated {
		notes = append(notes, "@deprecated")
	}
	g.docComment("  ", notes...)

	data := "void"
	if o.okSchema != nil {
		data = g.typeOf(o.okSchema)
	}
	errType := o.typeName + "Error"
	generics := data + ", " + errType
	if len(o.headers) > 0 {
		generics += ", " + o.typeName + "Headers"
	}
	input, arg := "", "{}"
	if o.hasInput() {
		opt := ""
		if o.inputOptional() {
			opt, arg = "?", "input ?? {}"
		} else {
			arg = "input"
		}
		input = fmt.Sprintf("input%s: %sInput, ", opt, o.typeName)
	}
	fmt.Fprintf(&g.buf, "  %s(%sinit?: RequestOptions): Promise<Result<%s>> {\n", o.id, input, generics)
	fmt.Fprintf(&g.buf, "    return this.send<%s>(%s, %s, init);\n  }\n", generics, o.spec(), arg)
}

func (o *operation) hasInput() bool { return len(o.params) > 0 || o.body != nil }

func (o *operation) inputOptional() bool {
	for _, p := range o.params {
		if p.Required {
			return false
		}
	}
	return o.body == nil || !o.body.Required
}

// spec writes the object literal the runtime needs to send the operation.
func (o *operation) spec() string {
	parts := []string{"method: " + tsString(o.method), "path: " + tsString(o.path)}
	if q := o.paramNames("query"); len(q) > 0 {
		parts = append(parts, "query: "+stringArray(q))
	}
	if h := o.paramNames("header"); len(h) > 0 {
		parts = append(parts, "headers: "+stringArray(h))
	}
	if o.body != nil {
		parts = append(parts, "body: true")
	}
	parts = append(parts, "ok: "+strconv.Itoa(o.okStatus))
	if o.okSchema != nil {
		parts = append(parts, "json: true")
	}
	if len(o.errors) > 0 {
		codes := make([]string, len(o.errors))
		for i, e := range o.errors {
			codes[i] = strconv.Itoa(e.status)
		}
		parts = append(parts, "errors: ["+strings.Join(codes, ", ")+"]")
	}
	if len(o.headers) > 0 {
		hs := make([]string, len(o.headers))
		for i, h := range o.headers {
			hs[i] = "[" + tsString(h.name) + ", " + tsString(h.kind) + "]"
		}
		parts = append(parts, "resHeaders: ["+strings.Join(hs, ", ")+"]")
	}
	if len(o.security) > 0 {
		alts := make([]string, len(o.security))
		for i, req := range o.security {
			alts[i] = stringArray(sortedKeys(req))
		}
		parts = append(parts, "security: ["+strings.Join(alts, ", ")+"]")
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

func (o *operation) paramNames(in string) []string {
	var names []string
	for _, p := range o.params {
		if p.In == in {
			names = append(names, p.Name)
		}
	}
	return names
}

func (g *generator) emitOperationTypes(o *operation) {
	if o.hasInput() {
		fmt.Fprintf(&g.buf, "export interface %sInput {\n", o.typeName)
		for _, p := range o.params {
			g.docComment("  ", p.Description, defaultTag(p.Schema))
			fmt.Fprintf(&g.buf, "  %s;\n", g.property(p.Name, p.Schema, p.Required))
		}
		if o.body != nil {
			g.docComment("  ", o.body.Description)
			fmt.Fprintf(&g.buf, "  %s;\n", g.property("body", o.bodySchema, o.body.Required))
		}
		g.buf.WriteString("}\n\n")
	}

	if len(o.errors) == 0 {
		fmt.Fprintf(&g.buf, "export type %sError = never;\n\n", o.typeName)
	} else {
		var parts []string
		for _, e := range o.errors {
			parts = append(parts, g.typeOf(e.schema))
		}
		fmt.Fprintf(&g.buf, "export type %sError = %s;\n\n", o.typeName, strings.Join(dedupe(parts), " | "))
	}

	if len(o.headers) > 0 {
		fmt.Fprintf(&g.buf, "export interface %sHeaders {\n", o.typeName)
		for _, h := range o.headers {
			g.docComment("  ", description(h.schema))
			fmt.Fprintf(&g.buf, "  %s;\n", g.property(h.name, h.schema, h.required))
		}
		g.buf.WriteString("}\n\n")
	}
}

func (g *generator) emitSchemas() {
	if g.doc.Components == nil {
		return
	}
	for _, name := range sortedKeys(g.doc.Components.Schemas) {
		s := g.doc.Components.Schemas[name]
		ts := g.names[name]
		if isPlainObject(s) {
			g.emitInterface(ts, s)
			continue
		}
		g.docComment("", s.Description)
		fmt.Fprintf(&g.buf, "export type %s = %s;\n\n", ts, g.typeOf(s))
	}
}

func (g *generator) emitRuntime() {
	var names []string
	if g.doc.Components != nil {
		names = sortedKeys(g.doc.Components.SecuritySchemes)
	}
	union := "never"
	if len(names) > 0 {
		union = strings.Join(quoteAll(names), " | ")
	}
	fmt.Fprintf(&g.buf, "/** The names in components.securitySchemes; the keys of ClientOptions.credentials. */\nexport type SecurityName = %s;\n\n", union)
	g.buf.WriteString("const securitySchemes: Record<string, { type: string; scheme?: string; in?: string; name?: string }> = {")
	for i, name := range names {
		s := g.doc.Components.SecuritySchemes[name]
		if i > 0 {
			g.buf.WriteString(",")
		}
		fmt.Fprintf(&g.buf, "\n  %s: { type: %s", propertyKey(name), tsString(s.Type))
		if s.Scheme != "" {
			fmt.Fprintf(&g.buf, ", scheme: %s", tsString(strings.ToLower(s.Scheme)))
		}
		if s.In != "" {
			fmt.Fprintf(&g.buf, ", in: %s", tsString(s.In))
		}
		if s.Name != "" {
			fmt.Fprintf(&g.buf, ", name: %s", tsString(s.Name))
		}
		g.buf.WriteString(" }")
	}
	if len(names) > 0 {
		g.buf.WriteString("\n")
	}
	g.buf.WriteString("};\n\n")
	g.buf.WriteString(runtime)
}

func description(s *openapi.Schema) string {
	if s == nil {
		return ""
	}
	return s.Description
}

func stringArray(items []string) string {
	return "[" + strings.Join(quoteAll(items), ", ") + "]"
}

func quoteAll(items []string) []string {
	out := make([]string, len(items))
	for i, s := range items {
		out[i] = tsString(s)
	}
	return out
}

func dedupe(items []string) []string {
	var out []string
	for _, s := range items {
		if !contains(out, s) {
			out = append(out, s)
		}
	}
	return out
}
